import {test,expect} from '@playwright/test'
test('真实 WebGL 工作台打开、连续前翻、后翻与关闭',async({page},testInfo)=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error'&&/WebGLProgram|shader error|VALIDATE_STATUS/i.test(m.text()))errors.push(m.text())})
 await page.goto('/')
 await expect(page.getByText('正在读取本地项目…')).toHaveCount(0)
 const canvas=page.locator('.canvas-host canvas')
 await expect(canvas).toBeVisible()
 const host=page.locator('.canvas-host')
 await page.getByRole('button',{name:'打开书籍',exact:true}).click()
 await expect(host).toHaveAttribute('data-page-ready','true',{timeout:12000})
 await expect(host).toHaveAttribute('data-page-gpu','chain-texture')
 await expect(host).toHaveAttribute('data-stack-geometry','layered')
 const pick=JSON.parse((await host.getAttribute('data-right-pick'))!) as [number,number]
 await page.mouse.move(...pick)
 await expect(host).toHaveAttribute('data-page-turn','preview')
 await expect.poll(async()=>Number(await host.getAttribute('data-hover-curl'))).toBeGreaterThan(.05)
 await expect(host).toHaveAttribute('data-page-progress','0')
 await expect(host).toHaveAttribute('data-page-index','0')
 await page.screenshot({path:testInfo.outputPath('local-hover.png')})
 await page.mouse.move(5,5)
 await expect(host).toHaveAttribute('data-page-turn','idle',{timeout:10000})
 await page.getByRole('button',{name:'下一页',exact:true}).click()
 await expect(host).toHaveAttribute('data-page-turn','active')
 await expect(host).toHaveAttribute('data-page-target','1')
 await expect(host).toHaveAttribute('data-page-index','1',{timeout:55000})
 await expect(host).toHaveAttribute('data-page-turn','idle')
 // Same input batch, using the real button handlers, eliminates a timing race
 // where the first leaf has landed before a second slow browser click.
 await page.getByRole('button',{name:'下一页',exact:true}).evaluate((button:HTMLButtonElement)=>{button.click();button.click()})
 await expect(host).toHaveAttribute('data-page-target','3')
 await expect.poll(async()=>Number(await host.getAttribute('data-peak-active-leaves'))).toBeGreaterThanOrEqual(2)
 if(Number(await host.getAttribute('data-active-leaves'))>=2)await page.screenshot({path:testInfo.outputPath('multiple-active-leaves.png')})
 await expect(host).toHaveAttribute('data-page-index','3',{timeout:55000})
 await page.screenshot({path:testInfo.outputPath('open-spread.png')})
 await page.getByRole('button',{name:'上一页',exact:true}).click()
 await expect(host).toHaveAttribute('data-page-index','2',{timeout:55000})
 await page.getByRole('button',{name:'闭合书籍',exact:true}).click()
 await expect(host).toHaveAttribute('data-page-ready','false')
 expect(errors).toEqual([])
})
