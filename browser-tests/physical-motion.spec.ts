import {test,expect} from '@playwright/test'
import {writeFile} from 'node:fs/promises'
test('自动物理厚度、千页导航、翻页中增页及原位几何守恒',async({page},info)=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/?perf=1');const host=page.locator('.canvas-host')
 await expect(host.locator('canvas')).toBeVisible({timeout:15000})
 const file=page.locator('input[type=file][accept=".json,application/json"]')
 await file.setInputFiles({name:'physical.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({version:1,thicknessMode:'automatic',paperThickness:.1,pageCount:320,pageIndex:80,pageDuration:2}))})
 await expect(page.locator('footer [role=status]')).toContainText('项目已导入')
 await expect(page.getByTestId('physical-thickness')).toContainText('21.00 mm')
 const metrics=async()=>JSON.parse((await host.getAttribute('data-stack-metrics'))!)
 await expect.poll(async()=> (await metrics()).configuredDepth).toBeCloseTo(.16,6)
 const revision=await host.getAttribute('data-geometry-revision')
 await page.getByRole('button',{name:'打开书籍',exact:true}).click()
 await expect(host).toHaveAttribute('data-page-ready','true',{timeout:25000})
 await expect(host).toHaveAttribute('data-page-index','80')
 await page.locator('.left').getByRole('button',{name:/内页/}).click()
 const count=page.getByRole('spinbutton',{name:'内页数量 数值'})
 await count.fill('800');await count.press('Enter')
 await expect.poll(async()=> (await metrics()).configuredDepth).toBeCloseTo(.4,6)
 await expect(host).toHaveAttribute('data-geometry-revision',revision!)
 await page.screenshot({path:info.outputPath('800-pages.png')})
 const next=page.locator('.viewport-bottom').getByRole('button',{name:'下一页',exact:true})
 await next.click();await expect(host).toHaveAttribute('data-page-turn','active')
 await count.fill('1000');await count.press('Enter')
 await expect.poll(async()=> (await metrics()).configuredDepth).toBeCloseTo(.5,6)
 await expect(host).toHaveAttribute('data-geometry-revision',revision!)
 await expect(host).toHaveAttribute('data-page-turn','active')
 const active=await metrics()
 expect(active.leftNominal+active.rightNominal+active.moving).toBeCloseTo(.5,6)
 await expect(host).toHaveAttribute('data-page-index','81',{timeout:25000})
 await expect(host).toHaveAttribute('data-page-turn','idle')
 const jump=page.getByRole('spinbutton',{name:'目标跨页 数值'})
 await jump.fill('250');await jump.press('Enter')
 await expect(host).toHaveAttribute('data-page-turn','active')
 await expect(host).toHaveAttribute('data-chunk-leaves','169')
 await expect(host).toHaveAttribute('data-page-index','250',{timeout:25000})
 await expect(host).toHaveAttribute('data-page-turn','idle')
 await expect(host).toHaveAttribute('data-geometry-revision',revision!)
 await count.fill('2000');await count.press('Enter')
 await expect.poll(async()=> (await metrics()).leaves).toBe(1000)
 await expect.poll(async()=> (await metrics()).configuredDepth).toBeCloseTo(1,6)
 await page.screenshot({path:info.outputPath('2000-pages.png')})
 const texture=JSON.parse((await host.getAttribute('data-texture-cache'))!)
 expect(texture.size).toBeLessThanOrEqual(texture.capacity);expect(texture.estimatedBytes).toBeLessThanOrEqual(texture.budgetBytes);expect(texture.hits).toBeGreaterThan(0)
 await writeFile(info.outputPath('physical-motion.json'),JSON.stringify({revision,metrics:await metrics(),texture,perf:JSON.parse((await host.getAttribute('data-perf'))!)},null,2))
 expect(errors).toEqual([])
})

test('自动规格极限薄纸与超厚窄书保持有限几何、旧项目手动尺寸兼容',async({page},info)=>{
 await page.emulateMedia({reducedMotion:'reduce'});await page.goto('/');const host=page.locator('.canvas-host')
 await expect(host.locator('canvas')).toBeVisible({timeout:15000})
 const file=page.locator('input[type=file][accept=".json,application/json"]'),errors:string[]=[]
 page.on('pageerror',e=>errors.push(e.message))
 const cases=[
  {name:'thin',pageCount:2,paperThickness:.04,boardThickness:.8,width:250,height:120,pageIndex:0,opening:180,expected:.0004},
  {name:'thick',pageCount:2000,paperThickness:.25,boardThickness:3,width:90,height:320,pageIndex:500,opening:180,expected:2.5}
 ]
 for(const {name,expected,...c} of cases){
  await file.setInputFiles({name:name+'.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({version:1,thicknessMode:'automatic',...c}))})
  await expect(page.locator('footer [role=status]')).toContainText('项目已导入')
  await expect(host).toHaveAttribute('data-page-ready','true',{timeout:20000})
  await expect.poll(async()=>JSON.parse((await host.getAttribute('data-stack-metrics'))!).configuredDepth).toBeCloseTo(expected,7)
  const m=JSON.parse((await host.getAttribute('data-stack-metrics'))!)
  expect(Object.values(m).every(Number.isFinite)).toBe(true)
  expect(m.leftNominal+m.rightNominal+m.moving).toBeCloseTo(expected,7)
  await page.screenshot({path:info.outputPath(name+'.png')})
 }
 await file.setInputFiles({name:'legacy.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({version:1,thickness:32,opening:180,pageCount:12}))})
 await expect(page.locator('footer [role=status]')).toContainText('项目已导入')
 await expect(page.getByRole('spinbutton',{name:'总厚度 数值'})).toHaveValue('32')
 await expect.poll(async()=>JSON.parse((await host.getAttribute('data-stack-metrics'))!).configuredDepth).toBeCloseTo(.27,6)
 expect(errors).toEqual([])
})
